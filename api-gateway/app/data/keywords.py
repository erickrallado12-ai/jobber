_KEYWORDS = sorted(set(_JOB_TITLES + _SKILLS))


def _normalize(text: str) -> str:
    return unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().lower()


def search_keywords(query: str, limit: int = 10) -> list[str]:
    if not query:
        return []
    q = _normalize(query)
    q_words = q.split()
    scored: list[tuple[int, int, int, str]] = []
    for kw in _KEYWORDS:
        nkw = _normalize(kw)
        if q in nkw:
            score = 1
        elif all(w in nkw for w in q_words):
            score = 2
        elif q_words and any(w in nkw for w in q_words):
            score = 3
        else:
            continue
        matched_count = sum(1 for w in q_words if w in nkw)
        scored.append((score, -matched_count, kw.lower().startswith(query.lower()) * -1, kw))
    scored.sort()
    return [kw for _, _, _, kw in scored[:limit]]
